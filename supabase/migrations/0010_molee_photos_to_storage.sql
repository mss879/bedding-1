-- Migration 0010: the Molee edit's photographs, served from Supabase Storage
--
-- Migration 0008 pointed the 80 Molee pieces at copies of their photographs
-- that ship with the website. This moves them onto the product-images bucket,
-- next to every photo uploaded in the dashboard, where they can be replaced
-- from the dashboard like any other.
--
-- SQL can say where a photograph lives but cannot carry the file, so the
-- files go into the bucket first, by hand:
--
--   1. Supabase → Storage → product-images.
--   2. Drag the folder public/images/products/molee from this repo into it.
--      The 320 photos then sit under molee/ in the bucket. (Dropped loose at the
--      top of the bucket instead works too.)
--   3. Run this file in the SQL editor.
--
-- It checks first that all 320 photos are in the bucket and stops without
-- changing anything if one is missing. It then repoints each piece, photo by
-- photo and in the same order, and leaves alone any photo already replaced in
-- the dashboard. Safe to run again: once moved, nothing is left to change.
--
-- Written for this project's Supabase address. On another project, regenerate
-- it or use `npm run photos:upload`, which uploads and repoints in one go.

