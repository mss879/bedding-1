DO $$
DECLARE
  missing integer;
  example text;
BEGIN
  SELECT count(*), min(p.file) INTO missing, example
    FROM molee_photos p
   WHERE NOT EXISTS (
     SELECT 1 FROM storage.objects o
      WHERE o.bucket_id = 'product-images'
        AND o.name IN ('molee/' || p.file, p.file)
   );
  IF missing > 0 THEN
    RAISE EXCEPTION '% of the 320 photos are not in the product-images bucket yet (for example %). Upload the molee folder to the bucket first, then run this again. Nothing was changed.', missing, example;
  END IF;
END $$;

UPDATE public.products AS p
   SET images = ARRAY(
     SELECT COALESCE(
              (SELECT 'https://dfvnesvowiideynfelva.supabase.co/storage/v1/object/public/product-images/' || o.name
                 FROM storage.objects o
                WHERE o.bucket_id = 'product-images'
                  AND t.photo LIKE '/images/products/molee/%'
                  AND o.name IN ('molee/' || substr(t.photo, 24), substr(t.photo, 24))
                ORDER BY o.name LIKE 'molee/%' DESC
                LIMIT 1),
              t.photo)
       FROM unnest(p.images) WITH ORDINALITY AS t(photo, position)
      ORDER BY t.position)
 WHERE EXISTS (SELECT 1 FROM unnest(p.images) AS i(photo) WHERE i.photo LIKE '/images/products/molee/%');

